// The test vectors in this file are taken from section 16 of the W3C
// Recommendation "Web Authentication: An API for accessing Public Key
// Credentials - Level 3", https://www.w3.org/TR/webauthn-3/#sctn-test-vectors.
// All of them use the RP ID example.org and the origin https://example.org.

// specVector is one pair of a registration and an authentication ceremony.
type specVector struct {
	// privateKey is the raw private key: the scalar of an ECDSA key or the
	// seed of an Ed25519 key. It is empty for the RSA key, which is derived.
	privateKey string
	aaguid     string
	// credentialID is the ID of the credential.
	credentialID string
	// regChallenge and regClientData are the inputs of the registration.
	regChallenge  string
	regClientData string
	// regAuthData is the authenticator data of the registration.
	regAuthData string
	// attestationObject is the attestation object of the registration. It is
	// only set for the vector that uses no attestation.
	attestationObject string
	// coseKey is the public key of the credential as a COSE_Key.
	coseKey string
	// authChallenge and authClientData are the inputs of the authentication.
	authChallenge  string
	authClientData string
	// authData and signature are the outputs of the authentication.
	authData  string
	signature string
}

